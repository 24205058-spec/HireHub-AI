/**
 * HireHub AI - Job Matcher Service
 * Deterministic AI heuristic simulation for candidate-job compatibility.
 */

const calculateSkillScore = (candidateSkills = [], jobSkills = []) => {
  if (!jobSkills || jobSkills.length === 0) return 100;
  if (!candidateSkills || candidateSkills.length === 0) return 20;

  const normalizedCandidate = candidateSkills.map(s => s.toLowerCase().trim());
  const normalizedJob = jobSkills.map(s => s.toLowerCase().trim());

  const matched = normalizedJob.filter(skill =>
    normalizedCandidate.some(cs => cs.includes(skill) || skill.includes(cs))
  );

  return Math.round((matched.length / normalizedJob.length) * 100);
};

const calculateExperienceScore = (candidateYears = 0, jobMinExp = 0, jobMaxExp = 5) => {
  if (candidateYears === undefined || candidateYears === null) return 60;
  if (candidateYears >= jobMinExp && candidateYears <= jobMaxExp + 2) return 100;
  if (candidateYears < jobMinExp) {
    const deficit = jobMinExp - candidateYears;
    return Math.max(30, 100 - deficit * 20);
  }
  const excess = candidateYears - (jobMaxExp + 2);
  return Math.max(65, 100 - excess * 5);
};

const calculateEducationScore = (education = []) => {
  if (!education || education.length === 0) return 60;
  const degrees = education.map(e => (e.degree || '').toLowerCase());
  const hasMasters = degrees.some(d => d.includes('master') || d.includes('msc') || d.includes('mba') || d.includes('m.tech'));
  const hasBachelors = degrees.some(d => d.includes('bachelor') || d.includes('bsc') || d.includes('b.tech') || d.includes('be') || d.includes('bs'));
  if (hasMasters) return 98;
  if (hasBachelors) return 85;
  return 70;
};

const calculateLocationScore = (candidateLocation = '', jobLocation = '', workMode = 'remote') => {
  if (workMode === 'remote' || !jobLocation || jobLocation.toLowerCase().includes('remote')) return 100;
  if (!candidateLocation) return 70;
  const cl = candidateLocation.toLowerCase();
  const jl = jobLocation.toLowerCase();
  if (cl.includes(jl) || jl.includes(cl)) return 100;
  return 60;
};

exports.calculateMatch = (candidateProfile, job) => {
  const skillScore = calculateSkillScore(candidateProfile?.skills, job?.skills);
  const experienceScore = calculateExperienceScore(
    candidateProfile?.yearsOfExperience || 0,
    job?.experience?.min || 0,
    job?.experience?.max || 5
  );
  const educationScore = calculateEducationScore(candidateProfile?.education);
  const locationScore = calculateLocationScore(candidateProfile?.location, job?.location, job?.workMode);

  const overallScore = Math.min(99, Math.max(25, Math.round(
    skillScore * 0.45 +
    experienceScore * 0.25 +
    educationScore * 0.15 +
    locationScore * 0.15
  )));

  const normalizedCandidate = (candidateProfile?.skills || []).map(s => s.toLowerCase().trim());
  const normalizedJob = (job?.skills || []).map(s => s.toLowerCase().trim());

  const matchedSkills = (job?.skills || []).filter(s =>
    normalizedCandidate.some(cs => cs.includes(s.toLowerCase().trim()) || s.toLowerCase().trim().includes(cs))
  );
  const missingSkills = (job?.skills || []).filter(s =>
    !normalizedCandidate.some(cs => cs.includes(s.toLowerCase().trim()) || s.toLowerCase().trim().includes(cs))
  );

  const explanation = [];
  explanation.push(`You match ${matchedSkills.length} of ${(job?.skills || []).length} required skills.`);
  if (missingSkills.length > 0) {
    explanation.push(`Recommended to acquire: ${missingSkills.slice(0, 3).join(', ')}.`);
  }
  if (experienceScore >= 85) {
    explanation.push('Your professional experience matches the requested profile.');
  } else {
    explanation.push('Experience gap detected relative to job requirement.');
  }

  return {
    overallScore,
    skillScore,
    experienceScore,
    educationScore,
    locationScore,
    matchedSkills,
    missingSkills,
    explanation,
    disclaimer: 'This score is generated by HireHub AI matching engine as guidance and does not guarantee hiring decisions.',
  };
};

exports.rankCandidates = (candidates, job) => {
  return candidates
    .map(candidate => {
      const profile = candidate.profile || candidate;
      return {
        ...candidate,
        matchResult: exports.calculateMatch(profile, job),
      };
    })
    .sort((a, b) => b.matchResult.overallScore - a.matchResult.overallScore);
};
